  cat <<EOF
RECOILJETS_THE96_AUAU_ISO_BASELINE5PCT_SUBMIT_V1
submit_host=$(hostname -f 2>/dev/null || hostname)
repo_root=${repo_root}
campaign_tag=${campaign_tag}
family=${family}
config_dir=${config_dir}
manifest=${manifest}
nominal_yaml=${nominal_yaml}
expanded_yaml=${expanded_yaml}
sim_group_size=${sim_group}
sim_memory=${sim_memory}
merge_group_size=${merge_group}
merge_memory=${merge_memory}
notify=${notify}
RJ_CODEX_CHAT_NAME=${RJ_CODEX_CHAT_NAME}
RJ_CODEX_THREAD_ID=${RJ_CODEX_THREAD_ID}
RJ_DAG_DRYRUN=${RJ_DAG_DRYRUN:-0}
RJ_DO_RUN=${do_run}

matrix:
  ranges: nominal_15to35, expanded_5to40
  lanes: baseline, topocluster
  datasets: isSimEmbedded Photon12+20; isSimEmbeddedInclusive Jet12+20+30+40
  hist views per ROOT: isoR30_fixedIso4GeV, isoR40_fixedIso4GeV, isoR30_isSliding, isoR40_isSliding
  photon-ID row: preselectionNewPPG12_tightReference_nonTightReference
EOF
}

heartbeat_prompt() {
  local prompt="${config_dir}/the96_heartbeat_prompt.txt"
  cat > "$prompt" <<EOF
Read-only heartbeat for THE-96 AuAu embedded isolation baseline 5%-centrality campaign.

Campaign tag: ${campaign_tag}
Manifest: ${manifest}
Config dir: ${config_dir}
Submit log: ${submit_log}

Objective:
- Monitor embedded signal and embedded inclusive/background Condor DAGs until the automatic SIM merge ladder finishes.
- Confirm final merged ROOT products exist for all manifest rows.
- Report ready-to-plot only when merged ROOT files are present and non-tiny.

Allowed:
- Read-only condor_q/condor_history/log/find/rootls checks.
- Run scripts/sdcc/workflows/submit/heartbeat_the96_auau_iso_baseline5pct_campaign.sh status ${campaign_tag}

Not allowed without fresh Justin approval:
- New submissions or resubmissions.
- condor_rm/hold/release.
- Deleting or moving outputs.
- Google Slides mutation.
EOF
  say "heartbeat_prompt=${prompt}"
}

case "$mode" in
  submit|print|heartbeat-prompt)
    prepare_configs
    prepare_manifest
    ;;
  help|-h|--help)
    usage
    exit 0
    ;;
  *)
    usage >&2
    die "unknown mode: ${mode}"
    ;;
esac

if [[ "$mode" == "heartbeat-prompt" ]]; then
  heartbeat_prompt
  exit 0
fi

exec > >(tee -a "$submit_log") 2>&1
print_contract
say "manifest rows:"
column -t -s $'\t' "$manifest" || cat "$manifest"

if [[ "$mode" == "print" || "$do_run" != "1" ]]; then
  preflight_outputs
  cat <<EOF

DRY_INTENT_ONLY=1
Set RJ_DO_RUN=1 to execute all eight embedded submits.
Set RJ_DAG_DRYRUN=1 with RJ_DO_RUN=1 to build/print DAGs without condor_submit_dag.
TRACK_THIS_CAMPAIGN=${campaign_tag}
SUBMIT_LOG=${submit_log}
MANIFEST=${manifest}
HEARTBEAT_CMD=scripts/sdcc/workflows/submit/heartbeat_the96_auau_iso_baseline5pct_campaign.sh watch ${campaign_tag}
EOF
  exit 0
fi

preflight_outputs
say "pre-submit queue snapshot"
condor_q -nobatch "${USER:-patsfan753}" 2>/dev/null | tail -80 || true

tail -n +2 "$manifest" | while IFS=$'\t' read -r range_key lane_key dataset yaml bulk_base merge_base topo_build topo_use; do
  [[ -n "$range_key" ]] || continue
  submit_row "$range_key" "$lane_key" "$dataset" "$yaml" "$bulk_base" "$merge_base" "$topo_build" "$topo_use"
done

say "post-submit queue snapshot"
condor_q -nobatch "${USER:-patsfan753}" 2>/dev/null | tail -120 || true
heartbeat_prompt

cat <<EOF

TRACK_THIS_CAMPAIGN=${campaign_tag}
SUBMIT_LOG=${submit_log}
MANIFEST=${manifest}
HEARTBEAT_CMD=scripts/sdcc/workflows/submit/heartbeat_the96_auau_iso_baseline5pct_campaign.sh watch ${campaign_tag}
EOF
