prepare_configs() {
  write_yaml "$nominal_yaml" "nominal_15to35" \
    "[15, 17, 19, 21, 23, 26, 35]" \
    "[15, 17, 19, 21, 23, 26, 35]" \
    "[15, 17, 19, 21, 23, 26, 35]"

  write_yaml "$expanded_yaml" "expanded_5to40" \
    "[5, 8, 10, 12, 14, 15, 17, 19, 21, 23, 26, 30, 35, 40]" \
    "[5, 8, 10, 12, 14, 15, 17, 19, 21, 23, 26, 30, 35, 40]" \
    "[5, 8, 10, 12, 14, 15, 17, 19, 21, 23, 26, 30, 35, 40]"
}

path_for_lane() {
  local range_key="$1"
  local lane_key="$2"
  printf '%s_%s_%s\n' "$campaign_tag" "$range_key" "$lane_key"
}

check_empty_or_allowed() {
  local path="$1"
  local label="$2"
  if [[ -e "$path" && "$allow_existing" != "1" ]]; then
    die "${label} already exists: ${path}. Set RJ_THE96_ALLOW_EXISTING=1 only for intentional resume/dry-run inspection." 5
  fi
}

prepare_manifest() {
  printf 'range\tlane\tdataset\tyaml\tbulk_base\tmerge_base\ttopo_build\ttopo_use\n' > "$manifest"

  local range_key lane_key yaml bulk_tag signal_bulk background_bulk merge_base topo_build topo_use
  for range_key in nominal_15to35 expanded_5to40; do
    case "$range_key" in
      nominal_15to35) yaml="$nominal_yaml" ;;
      expanded_5to40) yaml="$expanded_yaml" ;;
      *) die "unknown range key: $range_key" ;;
    esac
    for lane_key in baseline topocluster; do
      bulk_tag="$(path_for_lane "$range_key" "$lane_key")"
      rj_validate_campaign_tag "$bulk_tag" || exit 2
      signal_bulk="$(rj_bulk_signal_root_for_campaign "$family" "$bulk_tag")"
      background_bulk="$(rj_bulk_background_root_for_campaign "$family" "$bulk_tag")"
      merge_base="$(rj_merge_root_for_campaign "$bulk_tag")"
      topo_build=0
      topo_use=0
      if [[ "$lane_key" == "topocluster" ]]; then
        topo_build=1
        topo_use=1
      fi
      printf '%s\t%s\tisSimEmbedded\t%s\t%s\t%s\t%s\t%s\n' \
        "$range_key" "$lane_key" "$yaml" "$signal_bulk" "$merge_base" "$topo_build" "$topo_use" >> "$manifest"
      printf '%s\t%s\tisSimEmbeddedInclusive\t%s\t%s\t%s\t%s\t%s\n' \
        "$range_key" "$lane_key" "$yaml" "$background_bulk" "$merge_base" "$topo_build" "$topo_use" >> "$manifest"
    done
  done
}

preflight_outputs() {
  local row range_key lane_key dataset yaml bulk_base merge_base topo_build topo_use
  tail -n +2 "$manifest" | while IFS=$'\t' read -r range_key lane_key dataset yaml bulk_base merge_base topo_build topo_use; do
    [[ -n "$range_key" ]] || continue
    [[ -f "$yaml" ]] || die "missing generated YAML: $yaml"
    check_empty_or_allowed "$bulk_base" "${range_key}/${lane_key}/${dataset} bulk output"
    if [[ "$dataset" == "isSimEmbedded" ]]; then
      check_empty_or_allowed "$merge_base" "${range_key}/${lane_key} merge output"
    fi
  done
  if condor_q "${USER:-patsfan753}" -af ClusterId JobStatus Args 2>/dev/null | grep -F "$campaign_tag" >/dev/null; then
    condor_q "${USER:-patsfan753}" -af ClusterId JobStatus Args 2>/dev/null | grep -F "$campaign_tag" || true
    die "active Condor jobs already mention campaign tag ${campaign_tag}; refusing duplicate submit" 4
  fi
}

submit_row() {
  local range_key="$1"
  local lane_key="$2"
  local dataset="$3"
  local yaml="$4"
  local bulk_base="$5"
  local merge_base="$6"
  local topo_build="$7"
  local topo_use="$8"

  say "Submitting ${range_key}/${lane_key}/${dataset}"
  say "  yaml=${yaml}"
  say "  bulk_base=${bulk_base}"
  say "  merge_base=${merge_base}"
  say "  topo_build=${topo_build} topo_use=${topo_use}"

  common_env=(
    "RJ_NOTIFY_EMAILS=${notify}"
    "RJ_PROFILE_JOB=1"
    "RJ_JOB_HEARTBEAT_SECONDS=${RJ_JOB_HEARTBEAT_SECONDS:-0}"
    "RJ_CONFIG_YAML=${yaml}"
    "RJ_MERGE_OUT_BASE_OVERRIDE=${merge_base}"
    "RJ_REQUEST_MEMORY=${sim_memory}"
    "RJ_AUTO_MERGE=1"
    "RJ_SIM_FIRSTROUND_REQUEST_MEMORY=${merge_memory}"
    "RJ_SIM_MERGE_GROUP_SIZE=${merge_group}"
    "RJ_ID_FANOUT_MAX_ROWS=1"
    "RJ_PHOTON_ID_ROW_MATCH=preselectionNewPPG12_tightReference_nonTightReference"
    "RJ_INTERNAL_FIXED_ISO_GEV_AUAU=4.0"
    "RJ_AUAU_BUILD_TOPOCLUSTER_ISOLATION=${topo_build}"
    "RJ_AUAU_USE_TOPOCLUSTER_ISOLATION=${topo_use}"
    "RJ_AUAU_TOPOCLUSTER_EXCLUDE_CANDIDATE=${RJ_AUAU_TOPOCLUSTER_EXCLUDE_CANDIDATE:-0}"
    "RJ_CODEX_CHAT_NAME=${RJ_CODEX_CHAT_NAME}"
    "RJ_CODEX_THREAD_ID=${RJ_CODEX_THREAD_ID}"
  )

  if [[ "$dataset" == "isSimEmbedded" ]]; then
    env "${common_env[@]}" \
      "RJ_SIMEMBED_DEST_BASE=${bulk_base}" \
      ./RecoilJets_Condor_submit.sh isSimEmbedded condorDoAll groupSize "$sim_group"
  elif [[ "$dataset" == "isSimEmbeddedInclusive" ]]; then
    env "${common_env[@]}" \
      "RJ_SIMEMBEDINCLUSIVE_DEST_BASE=${bulk_base}" \
      "RJ_SIMEMBEDDEDINCLUSIVE_FOUR_SAMPLES=1" \
      ./RecoilJets_Condor_submit.sh isSimEmbeddedInclusive condorDoAll groupSize "$sim_group"
  else
    die "unsupported dataset: ${dataset}"
  fi
}

