#!/usr/bin/env bash
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
if [[ -f "${script_dir}/../../runtime/io/recoiljets_io_paths.sh" ]]; then
  source "${script_dir}/../../runtime/io/recoiljets_io_paths.sh"
elif [[ -f scripts/sdcc/runtime/io/recoiljets_io_paths.sh ]]; then
  source scripts/sdcc/runtime/io/recoiljets_io_paths.sh
else
  echo "[ERROR] Cannot locate scripts/sdcc/runtime/io/recoiljets_io_paths.sh" >&2
  exit 2
fi

repo_root="$(rj_find_repo_root "$script_dir")"
cd "$repo_root"

say() { printf '[THE96] %s\n' "$*"; }
die() { printf '[THE96][ERROR] %s\n' "$*" >&2; exit "${2:-2}"; }

mode="${1:-submit}"
campaign_tag="${RJ_THE96_CAMPAIGN_TAG:-the96_auau_iso_baseline5pct_$(date +%Y%m%d_%H%M)}"
family="${RJ_THE96_FAMILY:-auau_iso_baseline5pct}"
config_dir="${RJ_THE96_CONFIG_DIR:-${repo_root}/condor_generated_configs/${campaign_tag}}"
manifest="${RJ_THE96_MANIFEST:-${config_dir}/the96_campaign_manifest.tsv}"
notify="${RJ_NOTIFY_EMAILS:-just0131@gmail.com}"

rj_validate_campaign_tag "$campaign_tag" || exit 2
rj_validate_campaign_tag "$family" || exit 2

mkdir -p "$config_dir"
submit_log="${config_dir}/submit_${campaign_tag}.log"

sim_group="${RJ_THE96_SIM_GROUP_SIZE:-7}"
sim_memory="${RJ_THE96_SIM_MEMORY:-12000MB}"
merge_group="${RJ_THE96_MERGE_GROUP_SIZE:-75}"
merge_memory="${RJ_THE96_MERGE_MEMORY:-16000MB}"
allow_existing="${RJ_THE96_ALLOW_EXISTING:-0}"
do_run="${RJ_DO_RUN:-0}"

export RJ_CODEX_CHAT_NAME="${RJ_CODEX_CHAT_NAME:-THE-96_AuAu_Iso_Baseline_5pct}"
export RJ_CODEX_THREAD_ID="${RJ_CODEX_THREAD_ID:-${CODEX_THREAD_ID:-THE-96-local-codex-thread}}"

nominal_yaml="${config_dir}/analysis_config_${campaign_tag}_nominal_15to35.yaml"
expanded_yaml="${config_dir}/analysis_config_${campaign_tag}_expanded_5to40.yaml"

usage() {
  cat <<EOF
Usage:
  $0 submit
  $0 print
  $0 heartbeat-prompt

Environment:
  RJ_THE96_CAMPAIGN_TAG   default ${campaign_tag}
  RJ_DO_RUN=1             actually submit Condor DAGs
  RJ_DAG_DRYRUN=1         build/print DAGs without condor_submit_dag
  RJ_THE96_ALLOW_EXISTING=1 allow existing output roots for intentional resume checks

This campaign submits embedded Photon12+20 signal and embedded inclusive
Jet12+20+30+40 background for:
  - nominal 15-35 GeV and expanded 5-40 GeV photon ET binning
  - baseline tower-cone isolation and pp-style topocluster isolation lanes
  - internal histogram views isoR30_fixed, isoR40_fixed, isoR30_isSliding, isoR40_isSliding
EOF
}

