"""PPG12 Fig. 6 efficiency parity from the July 1 full pp SIM campaign.

Reproduces the slide plot previously generated by
scripts/plotting/pp_currentian/make_ppg12_fig6_our_pp_vs_sdcc_overlay_ratio.py,
but replaces the THE-85 nominal-only merged-ROOT input with the July 1
the76_ppg12_parity_full_20260701_003024 photon-jet SIM aggregate
(all periods and single+double components, photonjet5+10+20, unweighted sum,
matching the previous photonjet5plus10plus20 merge recipe).

Our-analysis efficiency math mirrors ppg12codeGit/plotting/plot_efficiency.C:
  reco        = Fig6Reco / TruthDen
  reco_id     = reco * (Fig6RecoTightIso / Fig6RecoIso)
  reco_id_iso = Fig6RecoTightIso / TruthDen
PPG12 side: reco = eff_reco_eta_0, reco_id = eff_reco*eff_id (conditional),
reco_id_iso = eff_all_eta_0 (as in ppg12codeGit/plotting/plot_efficiency.C).
"""

